import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { resolve, join } from 'node:path';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { pathToFileURL } from 'node:url';
const require = createRequire(resolve(process.argv[2], 'package.json'));
const { JSDOM } = require('jsdom');
const { build } = require('esbuild');
const dom = new JSDOM('<div id="root"></div>', { url: 'http://localhost' });
globalThis.window = dom.window;
globalThis.document = dom.window.document;
globalThis.HTMLElement = dom.window.HTMLElement;
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
const outfile = join(mkdtempSync(join(tmpdir(), 'rating-refresh-')), 'test.mjs');
await build({stdin:{contents:`export {createRoot} from 'react-dom/client'; export {act,createElement} from 'react'; export {EvaluationDetails} from './src/components/ratings/EvaluationDetails'; export {refresh,finish} from 'test-control';`,resolveDir:process.cwd()},outfile,bundle:true,format:'esm',platform:'node',jsx:'automatic',tsconfig:resolve('tsconfig.json'),plugins:[{name:'fixture',setup(b){
  b.onResolve({filter:/^test-control$|^@\/lib\/ratings\/repository$|^@\/lib\/live\/refresh$/},()=>({path:'control',namespace:'mock'}));
  b.onLoad({filter:/control/,namespace:'mock'},()=>({contents:`let callback, pending; let score=4; export function subscribeLiveRefresh(fn){callback=fn;return ()=>{callback=null;};} export function refresh(){return callback();} export function finish(){score++;pending([{avaliador_id:'a',avaliador_nome:'Avaliador',avaliado_id:'b',avaliado_nome:'Jogador',avaliado:true,passe:score,chute:4,velocidade:3,defesa:2,fisico:1}]);} export async function getEvaluationRounds(){return [{id:'round',nome:'Rodada',data:'2026-11-19'},{id:'other',nome:'Outra',data:'2026-11-12'}];} export function getEvaluationDetails(){return new Promise(resolve=>{pending=resolve;});}`,loader:'js'}));
  b.onResolve({filter:/^@\/components\/players\/PlayerIdentity$/},()=>({path:'identity',namespace:'mock'}));
  b.onLoad({filter:/identity/,namespace:'mock'},()=>({contents:'export function PlayerIdentity({name}){return name;}',loader:'js'}));
}}]});
const {createRoot,act,createElement,EvaluationDetails,refresh,finish}=await import(pathToFileURL(outfile));
const root=createRoot(document.getElementById('root'));
await act(async()=>root.render(createElement(EvaluationDetails,{roundId:'round'})));
const outer=document.querySelector('details');
await act(async()=>{outer.open=true;outer.dispatchEvent(new dom.window.Event('toggle'));});
await act(async()=>finish());
const evaluator=document.querySelector('details details');
assert(evaluator,'Evaluator must appear after initial load');
evaluator.open=true;
let refreshing;
await act(async()=>{refreshing=refresh();});
assert.equal(document.querySelector('details details'),evaluator,'Background refresh must not unmount the expanded evaluator');
assert.equal(evaluator.open,true);
assert(!document.body.textContent.includes('Carregando notas...'));
await act(async()=>{finish();await refreshing;});
assert.equal(document.querySelector('details details'),evaluator,'Update must retain the same DOM element');
assert.equal(evaluator.open,true);
assert(document.querySelector('dd').textContent.startsWith('6'),'Fresh scores must still render');
await act(async()=>{const select=document.querySelector('select');select.value='other';select.dispatchEvent(new dom.window.Event('change',{bubbles:true}));});
assert.equal(document.querySelector('details details'),null,'Changing rounds must not show previous notes');
await act(async()=>finish());
await act(async()=>root.unmount());
dom.window.close();
console.log('PASS: background refresh preserves evaluator DOM/open state; updates scores; round switch clears previous data');
// React's bundled scheduler can retain a MessagePort after the DOM is closed.
process.exit(0);
